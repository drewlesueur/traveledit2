const assert = require('node:assert/strict');
const { createControls } = require('./public/text-controls');
let changes = 0, closed = 0, selected;
const ui = createControls({ onChange() { changes++; }, onClose() { closed++; } });
let root;
const trigger = ui.button('[ Tools > ]', () => {
  root = ui.open('Tools');
  root.button('Display >', () => {
    const child = ui.open('Display', { parent: root });
    child.button('< Back', () => child.close());
    child.radioGroup('Quality', ['low', 'high'], 'low', value => { selected = value; });
    child.button('Unavailable', () => { throw Error('disabled action'); }, { disabled: true });
    ui.refresh({ focus: true });
  });
  ui.refresh({ focus: true });
});
ui.setContent([trigger]);
let lines;
function render(startRow = 10, viewportRows = 30) {
  lines = ui.render({ startRow, width: 24, viewportRows }).lines;
  assert.ok(lines.every(line => Array.from(line).length <= 24));
  return lines;
}
function activate(text, startRow = 10) {
  const index = lines.findIndex(line => line.includes(text));
  assert.ok(index >= 0, text);
  assert.equal(ui.activate(startRow + index, lines[index].startsWith('│') ? 1 : 0), true);
  render(startRow);
}
assert.deepEqual(render(), ['[ Tools > ]']);
const captured = ui.capture(10, 3);
render(20);
assert.deepEqual(ui.locate(captured), { row: 20, column: 3 });
render(); activate('Tools');
assert.ok(ui.isOpen); assert.ok(lines.some(line => line.startsWith('┌')));
activate('Display >'); activate('[ ] high');
assert.equal(selected, 'high'); assert.ok(lines.some(line => line.includes('[x] high')));
activate('Unavailable');
activate('< Back'); assert.equal(root.isOpen, true);
root.setDisabled(true); render(); activate('Display >');
assert.ok(!lines.some(line => line.includes('Quality')));
root.setDisabled(false); render();
const second = createControls(); second.open('Independent');
assert.equal(ui.activate(500, 0), true); assert.equal(closed, 1);
assert.equal(second.isOpen, true); assert.ok(changes > 0);
render(10, 12); activate('Tools'); render(10, 12);
assert.ok(lines[0].startsWith('┌'), 'popup goes above trigger near viewport end');
assert.ok(ui.isControlRow(10));
ui.destroy(); assert.deepEqual(ui.render().lines, []);
second.destroy();
console.log('Inline TravelEdit text-control checks passed');

const form = createControls();
const popup = form.open('Editable settings');
const instructions = popup.field('Instructions', 'first\nsecond', { multiline: true });
popup.field('Limit', '5');
let rendered = form.render({ startRow: 10 }).lines;
let firstRow = 10 + rendered.indexOf('first');
assert.equal(form.fieldAt(firstRow).node, instructions);
assert.equal(form.fieldAt(firstRow + 1).fieldLine, 1);
assert.equal(form.activate(firstRow, 2), false, 'field taps enter native editing');
assert.equal(form.isOpen, true);
const fieldCursor = form.capture(firstRow + 1, 3);
form.render({ startRow: 20 });
assert.deepEqual(form.locate(fieldCursor), { row: firstRow + 11, column: 3 });
popup.setDisabled(true); form.render({ startRow: 20 });
assert.equal(form.fieldAt(firstRow + 10), null);
form.destroy();
console.log('Inline TravelEdit editable-field checks passed');

const unicode = createControls();
const unicodePopup = unicode.open('Unicode fields');
const unicodeField = unicodePopup.field('Text', '😀');
const measure = text => Array.from(text).reduce((size, char) => size + (char === '😀' ? 2 : 1), 0);
let unicodeLines = unicode.render({ startRow: 0, measure }).lines;
let unicodeRow = unicodeLines.indexOf('😀');
const unicodeCursor = unicode.capture(unicodeRow, 2);
assert.equal(unicodeCursor.node, unicodeField);
unicode.render({ startRow: 4, measure });
assert.deepEqual(unicode.locate(unicodeCursor), { row: unicodeRow + 4, column: 2 }, 'keep caret after a wide character');
const extendedCursor = unicode.capture(unicodeRow + 4, 6);
unicodeField.value = '😀hello';
unicode.render({ startRow: 8, measure });
assert.equal(unicode.locate(extendedCursor).column, 6, 'typing past the old field end preserves the new column');
unicode.destroy();
console.log('Inline TravelEdit Unicode-field checks passed');

const horizontal = createControls();
let clicked = '';
const firstButton = horizontal.button('[ First ]', () => { clicked = 'first'; });
const lastButton = horizontal.button('[ Last action ]', () => { clicked = 'last'; });
horizontal.setContent([firstButton, lastButton], { layout: 'row' });
let horizontalLines = horizontal.render({ width: 8, startRow: 5 }).lines;
assert.deepEqual(horizontalLines, ['[ First ] [ Last action ]'], 'row never clips or wraps at the viewport width');
assert.equal(horizontal.activate(5, 9), false, 'separator is not a button');
horizontal.activate(5, 12);
assert.equal(clicked, 'last', 'offscreen button retains its own hit region');
const lastCursor = horizontal.capture(5, 12);
firstButton.label = '[ Longer first label ]';
horizontal.render({ width: 8, startRow: 7 });
assert.deepEqual(horizontal.locate(lastCursor), { row: 7, column: 25 });
lastButton.disabled = true;
horizontal.render({ width: 8, startRow: 7 });
clicked = '';
horizontal.activate(7, 25);
assert.equal(clicked, '', 'disabled row button does not activate');
const rowPopup = horizontal.open('Options'); rowPopup.button('One', () => {}); rowPopup.button('Two', () => {});
horizontalLines = horizontal.render({ width: 20, startRow: 0, viewportRows: 7 }).lines;
assert.equal(horizontalLines[0], '[ Longer first label ] [ Last action ]', 'one root row fits above the popup');
assert.ok(horizontalLines[2].includes('One') && horizontalLines[3].includes('Two'), 'popup choices remain vertical');
horizontal.destroy();
console.log('Inline TravelEdit horizontal-control checks passed');

const floating = createControls();
floating.setContent([floating.button('[ Open ]', () => {})], { layout: 'row' });
const beforeOverlay = floating.render({ startRow: 10, overlay: true });
const floatingPopup = floating.open('Settings');
let overlayClicked = false;
floatingPopup.button('[ Choose ]', () => { overlayClicked = true; });
const afterOverlay = floating.render({ startRow: 10, viewportRows: 30, overlay: true });
assert.deepEqual(afterOverlay.lines, beforeOverlay.lines, 'popup does not insert document rows');
assert.equal(afterOverlay.overlay.row, 11);
assert.equal(afterOverlay.overlay.column, 0);
assert.ok(afterOverlay.overlay.lines[0].includes('Settings'));
floating.activate(12, 2);
assert.equal(overlayClicked, true, 'popup hit regions use overlay coordinates');
const upperOverlay = floating.render({ startRow: 20, viewportRows: 23, overlay: true });
assert.equal(upperOverlay.overlay.row, 16, 'popup can overlay rows above the trigger');
assert.deepEqual(upperOverlay.lines, beforeOverlay.lines);
floating.closeAll();
assert.equal(floating.render({ startRow: 10, overlay: true }).overlay, null);
floating.destroy();
console.log('Inline TravelEdit overlay checks passed');
